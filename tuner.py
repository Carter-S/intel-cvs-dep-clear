class Handler(http.server.BaseHTTPRequestHandler):
    def log_message(self, *a):
        pass

    def _send(self, code, body, ctype="text/plain"):
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body if isinstance(body, bytes) else body.encode())

    def do_GET(self):
        if self.path == "/":
            self._send(200, PAGE, "text/html")
        elif self.path.startswith("/preview.jpg"):
            frame, _ = capture.wait_frame(-1, timeout=3)
            if frame:
                self._send(200, frame, "image/jpeg")
            else:
                self._send(404, "no frame yet")
        elif self.path.startswith("/stream"):
            self.mjpeg_stream()
        elif self.path == "/state":
            self._send(200, json.dumps(load_state()), "application/json")
        else:
            self._send(404, "not found")

    def mjpeg_stream(self):
        """Serve frames from the single shared Capture thread."""
        boundary = "tunerframe"
        self.send_response(200)
        self.send_header("Content-Type",
                         f"multipart/x-mixed-replace;boundary={boundary}")
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        seq = -1
        try:
            while True:
                frame, seq = capture.wait_frame(seq)
                if frame is None:
                    continue  # capture warming up; keep the client waiting
                self.wfile.write(
                    f"--{boundary}\r\n"
                    f"Content-Type: image/jpeg\r\n"
                    f"Content-Length: {len(frame)}\r\n\r\n".encode()
                    + frame + b"\r\n")
        except (BrokenPipeError, ConnectionResetError):
            pass  # client left

    def do_POST(self):
        if self.path == "/apply":
            n = int(self.headers.get("Content-Length", 0))
            try:
                p = {**DEFAULTS, **json.loads(self.rfile.read(n))}
                p = {k: float(p[k]) for k in DEFAULTS}
            except Exception as e:
                return self._send(400, f"bad request: {e}")
        elif self.path == "/reset":
            p = dict(DEFAULTS)
        else:
            return self._send(404, "not found")
        try:
            with state_lock:
                capture.bounce()  # release the device during the restart
                apply_state(p)
            self._send(200, json.dumps(p), "application/json")
        except Exception as e:
            self._send(500, f"apply failed: {e}")


def main():
    if os.geteuid() != 0:
        raise SystemExit("run with sudo (writes system config + restarts the relay)")
    capture.start()
    srv = http.server.ThreadingHTTPServer(("127.0.0.1", PORT), Handler)
    print(f"Camera tuner: http://127.0.0.1:{PORT}")
    print("NOTE: while this runs, other apps cannot use the camera.")
    try:
        srv.serve_forever()
    except KeyboardInterrupt:
        capture.stop_flag = True
        capture.bounce()


if __name__ == "__main__":
    main()

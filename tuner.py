#!/usr/bin/env python3
"""Interactive camera tuner for the libcamera softISP + v4l2-relayd stack.

Run:  sudo python3 tuner.py    then open http://127.0.0.1:8787

Writes /usr/share/libcamera/ipa/simple/ov08x40.yaml (CCM from the
saturation + RGB gain sliders) and /etc/v4l2-relayd.d/camera.conf
(gst post-processing from brightness/contrast/gamma sliders), restarts
v4l2-relayd@camera, and shows a live 30fps preview.

NOTE: the virtual camera only supports ONE reader at a time. While this
tuner runs, other apps (Meet, Zoom...) cannot use the camera. Ctrl-C the
tuner when you're done, then join your call.
"""
import http.server
import json
import os
import subprocess
import threading
import time

PORT = 8787


def find_device(label="Virtual Camera"):
    import glob
    for n in glob.glob("/sys/devices/virtual/video4linux/*/name"):
        try:
            with open(n) as fh:
                if fh.read().strip() == label:
                    return "/dev/" + n.split("/")[-2]
        except OSError:
            pass
    raise SystemExit("no v4l2loopback device labelled 'Virtual Camera' - "
                     "run setup-relay.sh first")


DEVICE = find_device()
YAML_PATH = "/usr/share/libcamera/ipa/simple/ov08x40.yaml"
CONF_PATH = "/etc/v4l2-relayd.d/camera.conf"
STATE_PATH = "/etc/v4l2-relayd.d/tuner-state.json"
SERVICE = "v4l2-relayd@camera.service"

DEFAULTS = {
    "saturation": 1.35,
    "gain_r": 1.03,
    "gain_g": 0.93,
    "gain_b": 1.03,
    "brightness": 0.0,
    "contrast": 1.0,
    "gamma": 1.0,
    "hflip": 0.0,
    "agc_target": 2.5,
}

LUMA = (0.2126, 0.7152, 0.0722)

state_lock = threading.Lock()


def compute_ccm(sat, gr, gg, gb):
    rows = []
    for i, gain in enumerate((gr, gg, gb)):
        row = [((1 - sat) * LUMA[j] + (sat if i == j else 0)) * gain
               for j in range(3)]
        rows.append(row)
    return rows


def yaml_text(p):
    m = compute_ccm(p["saturation"], p["gain_r"], p["gain_g"], p["gain_b"])
    f = [f"{v:.4f}" for row in m for v in row]
    ccm = (f"[ {f[0]}, {f[1]}, {f[2]},\n"
           f"                {f[3]}, {f[4]}, {f[5]},\n"
           f"                {f[6]}, {f[7]}, {f[8]} ]")
    return f"""# SPDX-License-Identifier: CC0-1.0
# Generated by cvs-dep-clear tuner.py - hand calibration, not factory data
%YAML 1.1
---
version: 1
algorithms:
  - BlackLevel:
  - Awb:
  - Ccm:
      ccms:
        - ct: 2860
          ccm: {ccm}
        - ct: 6500
          ccm: {ccm}
  - Adjust:
  - Agc:
...
"""


def conf_text(p):
    post = ""
    if p["hflip"]:
        post += " ! videoflip method=horizontal-flip"
    if p["brightness"] != 0 or p["contrast"] != 1:
        post += (f" ! videobalance brightness={p['brightness']:.2f}"
                 f" contrast={p['contrast']:.2f}")
    if p["gamma"] != 1:
        post += f" ! gamma gamma={p['gamma']:.2f}"
    return ('VIDEOSRC="libcamerasrc ! '
            "video/x-raw,format=RGBA,width=1280,height=720,framerate=30/1"
            f"{post} ! videoconvert\"\n"
            # read by the (optionally patched) softISP AGC; harmless otherwise
            f"SOFTISP_AGC_TARGET={p['agc_target']:.2f}\n")


def load_state():
    try:
        with open(STATE_PATH) as fh:
            saved = json.load(fh)
        return {**DEFAULTS, **{k: saved[k] for k in DEFAULTS if k in saved}}
    except Exception:
        return dict(DEFAULTS)


def apply_state(p):
    with open(YAML_PATH, "w") as fh:
        fh.write(yaml_text(p))
    with open(CONF_PATH, "w") as fh:
        fh.write(conf_text(p))
    with open(STATE_PATH, "w") as fh:
        json.dump(p, fh, indent=2)
    subprocess.run(["systemctl", "restart", SERVICE], check=True, timeout=30)


class Capture(threading.Thread):
    """THE single reader of the virtual camera (the loopback allows only
    one). Parses the JPEG stream and fans frames out to all HTTP clients."""

    def __init__(self):
        super().__init__(daemon=True)
        self.cond = threading.Condition()
        self.frame = None
        self.seq = 0
        self.proc = None
        self.stop_flag = False

    def run(self):
        soi = b"\xff\xd8\xff"
        while not self.stop_flag:
            self.proc = subprocess.Popen(
                ["gst-launch-1.0", "-q",
                 "v4l2src", f"device={DEVICE}", "!",
                 "videoconvert", "!", "jpegenc", "quality=80", "!",
                 "fdsink"],
                stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
            buf = b""
            while True:
                chunk = self.proc.stdout.read(65536)
                if not chunk:
                    break  # died (relay restart / warm-up race): respawn
                buf += chunk
                while True:
                    first = buf.find(soi)
                    nxt = buf.find(soi, first + 3) if first >= 0 else -1
                    if nxt < 0:
                        if first > 0:
                            buf = buf[first:]
                        break
                    frame, buf = buf[first:nxt], buf[nxt:]
                    with self.cond:
                        self.frame = frame
                        self.seq += 1
                        self.cond.notify_all()
            self.proc.kill()
            if not self.stop_flag:
                time.sleep(1.0)

    def bounce(self):
        if self.proc and self.proc.poll() is None:
            self.proc.kill()

    def wait_frame(self, last_seq, timeout=5.0):
        with self.cond:
            self.cond.wait_for(lambda: self.seq != last_seq, timeout=timeout)
            return self.frame, self.seq


capture = Capture()

